const fs = require("node:fs");
const path = require("node:path");

const read = name => fs.readFileSync(path.join(__dirname, name), "utf8").replace(/\r\n/g, "\n");
const manifest = JSON.parse(read("manifest.json"));
const [page] = manifest.content_scripts;
const rawUrl = "https://raw.githubusercontent.com/What-a-mess/kick-danmaku/main/kick-danmaku.user.js";
const banner = "// Generated by build-userscript.cjs.";
const popupBody = read("popup.html").match(/<body>([\s\S]+)<\/body>/)[1].trim();
const popupCss = read("popup.css").replace(/^:root/m, ":host").replace(/^body\s*\{[^}]+}/m,
  ".settings-content { width: 100%; padding: 16px; }");
const panelTemplate = `${banner}
const kickDanmakuPanelMarkup = ${JSON.stringify(popupBody)};
const kickDanmakuPanelStyles = ${JSON.stringify(popupCss)};
`;
const userscript = `// ==UserScript==
// @name         Kick 弹幕
// @namespace    https://github.com/What-a-mess/kick-danmaku
// @version      ${manifest.version}
// @description  将 Kick 实时聊天显示为播放器弹幕
// @match        https://kick.com/*
// @match        https://www.kick.com/*
// @run-at       document-idle
// @noframes
// @sandbox      DOM
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_addValueChangeListener
// @grant        GM_addStyle
// @grant        GM_registerMenuCommand
// @downloadURL  ${rawUrl}
// @updateURL    ${rawUrl}
// ==/UserScript==

${banner}
(() => {
"use strict";
GM_addStyle(${JSON.stringify(page.css.map(read).join("\n"))});
${page.js.map(name => name === "panel-template.js" ? panelTemplate : read(name)).join("\n")}
})();
`;

for (const [name, content] of [["panel-template.js", panelTemplate], ["kick-danmaku.user.js", userscript]]) {
  if (process.argv.includes("--check")) {
    if (read(name) !== content) {
      console.error(`${name} is out of date. Run node build-userscript.cjs.`);
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(path.join(__dirname, name), content);
  }
}
